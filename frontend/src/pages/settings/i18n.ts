export const dicts: Record<Lang, Dict> = { EN: en, PT: pt, ES: es }
export type Key = keyof Dict

// t('key', { n: 3 }) with {placeholders}; values are plain text (templates escape them)
export function useT() {
  const lang = useLangStore()
  const d = computed(() => dicts[lang.lang])
  return (key: Key, vars: Record<string, string | number> = {}) =>
    d.value[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

// theme names are proper names; only their descriptive words are translated
const words: Record<Lang, [RegExp, string][]> = {
  EN: [],
  PT: [
    [/\(dark\)/, '(escuro)'],
    [/^Default$/, 'Padrão'],
    [/^High contrast/, 'Alto contraste'],
  ],
  ES: [
    [/\(dark\)/, '(oscuro)'],
    [/^Default$/, 'Predeterminado'],
    [/^High contrast/, 'Alto contraste'],
  ],
}
export function themeLabel(label: string, lang: Lang): string {
  return words[lang].reduce((s, [re, to]) => s.replace(re, to), label)
}
